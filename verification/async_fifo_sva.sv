`timescale 1ns/1ps
module async_fifo_sva #(
  parameter int unsigned ADDR_WIDTH = 5
)(
  input logic clk_wr,
  input logic clk_rd,
  input logic wr_rst_n,
  input logic rd_rst_n,
  input logic wr_en,
  input logic rd_en,
  input logic full,
  input logic empty,
  input logic [ADDR_WIDTH:0] wr_bin,
  input logic [ADDR_WIDTH:0] wr_gray,
  input logic [ADDR_WIDTH:0] wr_bin_next,
  input logic [ADDR_WIDTH:0] wr_gray_next,
  input logic [ADDR_WIDTH:0] rd_bin,
  input logic [ADDR_WIDTH:0] rd_gray,
  input logic [ADDR_WIDTH:0] rd_bin_next,
  input logic [ADDR_WIDTH:0] rd_gray_next,
  input logic [ADDR_WIDTH:0] wr_gray_sync_to_rd,
  input logic [ADDR_WIDTH:0] rd_sync_gray_to_wr,
  input logic full_next,
  input logic empty_next
);

  localparam int unsigned PTR_WIDTH = ADDR_WIDTH + 1;
  localparam logic [PTR_WIDTH-1:0] FULL_COMPARE_MASK = {
    2'b11, {(PTR_WIDTH-2){1'b0}}
  };

  initial
    $display("[%0t] INFO: async_fifo_sva bound (ADDR_WIDTH=%0d)",
             $time, ADDR_WIDTH);

  // Reset must leave each local domain in its conservative safe state.
  property p_write_reset_state;
    @(posedge clk_wr)
    !wr_rst_n |-> (wr_bin == '0 && wr_gray == '0 && full == 1'b0);
  endproperty

  property p_read_reset_state;
    @(posedge clk_rd)
    !rd_rst_n |-> (rd_bin == '0 && rd_gray == '0 && empty == 1'b1);
  endproperty

  // Binary and Gray representations must describe the same local pointer.
  property p_write_gray_matches_binary;
    @(posedge clk_wr) disable iff (!wr_rst_n)
    wr_gray == ((wr_bin >> 1) ^ wr_bin);
  endproperty

  property p_read_gray_matches_binary;
    @(posedge clk_rd) disable iff (!rd_rst_n)
    rd_gray == ((rd_bin >> 1) ^ rd_bin);
  endproperty

  // Next-state logic may advance only for an accepted local transaction.
  property p_write_next_state;
    @(posedge clk_wr) disable iff (!wr_rst_n)
    wr_bin_next ==
      (wr_bin + {{(PTR_WIDTH-1){1'b0}}, (wr_en && !full)}) &&
    wr_gray_next == ((wr_bin_next >> 1) ^ wr_bin_next);
  endproperty

  property p_read_next_state;
    @(posedge clk_rd) disable iff (!rd_rst_n)
    rd_bin_next ==
      (rd_bin + {{(PTR_WIDTH-1){1'b0}}, (rd_en && !empty)}) &&
    rd_gray_next == ((rd_bin_next >> 1) ^ rd_bin_next);
  endproperty

  // A valid transaction advances exactly once; a rejected or idle request
  // leaves both pointer representations unchanged.
  property p_accepted_write_advances;
    @(posedge clk_wr) disable iff (!wr_rst_n)
    (wr_en && !full) |=>
      (wr_bin == ($past(wr_bin) + {{(PTR_WIDTH-1){1'b0}}, 1'b1}));
  endproperty

  property p_unaccepted_write_is_stable;
    @(posedge clk_wr) disable iff (!wr_rst_n)
    !(wr_en && !full) |=> ($stable(wr_bin) && $stable(wr_gray));
  endproperty

  property p_accepted_read_advances;
    @(posedge clk_rd) disable iff (!rd_rst_n)
    (rd_en && !empty) |=>
      (rd_bin == ($past(rd_bin) + {{(PTR_WIDTH-1){1'b0}}, 1'b1}));
  endproperty

  property p_unaccepted_read_is_stable;
    @(posedge clk_rd) disable iff (!rd_rst_n)
    !(rd_en && !empty) |=> ($stable(rd_bin) && $stable(rd_gray));
  endproperty

  // Gray pointers generated by adjacent accepted transactions change no more
  // than one bit in their source domains.
  property p_write_gray_one_bit;
    @(posedge clk_wr) disable iff (!wr_rst_n)
    $past(wr_rst_n) |-> $onehot0(wr_gray ^ $past(wr_gray));
  endproperty

  property p_read_gray_one_bit;
    @(posedge clk_rd) disable iff (!rd_rst_n)
    $past(rd_rst_n) |-> $onehot0(rd_gray ^ $past(rd_gray));
  endproperty

  // Flag equations use next local pointers and synchronized remote pointers.
  property p_full_next_equation;
    @(posedge clk_wr) disable iff (!wr_rst_n)
    full_next ==
      (wr_gray_next == (rd_sync_gray_to_wr ^ FULL_COMPARE_MASK));
  endproperty

  property p_empty_next_equation;
    @(posedge clk_rd) disable iff (!rd_rst_n)
    empty_next == (rd_gray_next == wr_gray_sync_to_rd);
  endproperty

  // Registered flags must equal the next-state result sampled one local cycle
  // earlier. The past-reset guard avoids checking uninitialized history.
  property p_full_registered;
    @(posedge clk_wr) disable iff (!wr_rst_n)
    $past(wr_rst_n) |-> (full == $past(full_next));
  endproperty

  property p_empty_registered;
    @(posedge clk_rd) disable iff (!rd_rst_n)
    $past(rd_rst_n) |-> (empty == $past(empty_next));
  endproperty

  a_write_reset_state: assert property (p_write_reset_state)
    else $fatal(1, "SVA: invalid write-domain reset state");
  a_read_reset_state: assert property (p_read_reset_state)
    else $fatal(1, "SVA: invalid read-domain reset state");
  a_write_gray_matches_binary: assert property (p_write_gray_matches_binary)
    else $fatal(1, "SVA: write Gray pointer does not match binary pointer");
  a_read_gray_matches_binary: assert property (p_read_gray_matches_binary)
    else $fatal(1, "SVA: read Gray pointer does not match binary pointer");
  a_write_next_state: assert property (p_write_next_state)
    else $fatal(1, "SVA: invalid write-pointer next state");
  a_read_next_state: assert property (p_read_next_state)
    else $fatal(1, "SVA: invalid read-pointer next state");
  a_accepted_write_advances: assert property (p_accepted_write_advances)
    else $fatal(1, "SVA: accepted write did not advance exactly once");
  a_unaccepted_write_is_stable: assert property (p_unaccepted_write_is_stable)
    else $fatal(1, "SVA: write pointer advanced without an accepted write");
  a_accepted_read_advances: assert property (p_accepted_read_advances)
    else $fatal(1, "SVA: accepted read did not advance exactly once");
  a_unaccepted_read_is_stable: assert property (p_unaccepted_read_is_stable)
    else $fatal(1, "SVA: read pointer advanced without an accepted read");
  a_write_gray_one_bit: assert property (p_write_gray_one_bit)
    else $fatal(1, "SVA: write Gray pointer changed by more than one bit");
  a_read_gray_one_bit: assert property (p_read_gray_one_bit)
    else $fatal(1, "SVA: read Gray pointer changed by more than one bit");
  a_full_next_equation: assert property (p_full_next_equation)
    else $fatal(1, "SVA: full_next equation mismatch");
  a_empty_next_equation: assert property (p_empty_next_equation)
    else $fatal(1, "SVA: empty_next equation mismatch");
  a_full_registered: assert property (p_full_registered)
    else $fatal(1, "SVA: full is not the registered full_next value");
  a_empty_registered: assert property (p_empty_registered)
    else $fatal(1, "SVA: empty is not the registered empty_next value");

  // Functional coverage demonstrates that the regression reaches both
  // boundaries and wraps the address portion of each pointer.
  c_final_write_asserts_full: cover property (
    @(posedge clk_wr) disable iff (!wr_rst_n)
    (wr_en && !full) |=> full);
  c_final_read_asserts_empty: cover property (
    @(posedge clk_rd) disable iff (!rd_rst_n)
    (rd_en && !empty) |=> empty);
  c_write_pointer_wraps: cover property (
    @(posedge clk_wr) disable iff (!wr_rst_n)
    (wr_en && !full && (&wr_bin[ADDR_WIDTH-1:0])) |=>
      (wr_bin[ADDR_WIDTH-1:0] == '0));
  c_read_pointer_wraps: cover property (
    @(posedge clk_rd) disable iff (!rd_rst_n)
    (rd_en && !empty && (&rd_bin[ADDR_WIDTH-1:0])) |=>
      (rd_bin[ADDR_WIDTH-1:0] == '0));

endmodule

bind async_fifo async_fifo_sva #(
  .ADDR_WIDTH(ADDR_WIDTH)
) async_fifo_sva_i (
  .clk_wr(clk_wr),
  .clk_rd(clk_rd),
  .wr_rst_n(wr_rst_n),
  .rd_rst_n(rd_rst_n),
  .wr_en(wr_en),
  .rd_en(rd_en),
  .full(full),
  .empty(empty),
  .wr_bin(wr_bin),
  .wr_gray(wr_gray),
  .wr_bin_next(wr_bin_next),
  .wr_gray_next(wr_gray_next),
  .rd_bin(rd_bin),
  .rd_gray(rd_gray),
  .rd_bin_next(rd_bin_next),
  .rd_gray_next(rd_gray_next),
  .wr_gray_sync_to_rd(wr_gray_sync_to_rd),
  .rd_sync_gray_to_wr(rd_sync_gray_to_wr),
  .full_next(full_next),
  .empty_next(empty_next)
);
